import LayoutPilotCore

func modifierGestureChecks() -> [(Bool, String)] {
    var results: [(Bool, String)] = []
    func check(_ value: Bool, _ name: String) { results.append((value, "modifier: " + name)) }
    var m = ModifierGesture(optionTap: true, bothShiftPause: true)
    // Explicit element type: the untyped literal exceeds the Linux type-checker budget.
    let releaseCases: [(Int, UInt64, UInt64)] = [(56, 0x2, 1 << 17), (60, 0x4, 1 << 17),
        (58, 0x20, 1 << 19), (61, 0x40, 1 << 19), (55, 0x8, 1 << 20),
        (54, 0x10, 1 << 20), (59, 0x1, 1 << 18), (62, 0x2000, 1 << 18)]
    for (key, side, aggregate) in releaseCases {
        check(ModifierGesture.isRelease(keyCode: key, rawFlags: 0), "known modifier release \(key)")
        check(!ModifierGesture.isRelease(keyCode: key, rawFlags: side | aggregate), "held modifier is not release \(key)")
        check(!ModifierGesture.isRelease(keyCode: key, rawFlags: aggregate), "missing side bits do not prove release \(key)")
    }
    check(ModifierGesture.isRelease(keyCode: 55, rawFlags: 0x10 | (1 << 20)), "left Command released while right remains held")
    check(ModifierGesture.isRelease(keyCode: 58, rawFlags: 0x8 | (1 << 20)), "Option release with Command held")
    check(!ModifierGesture.isRelease(keyCode: 57, rawFlags: 0), "unknown modifier cannot preserve replay context")
    check(m.modifier(keyCode: 56, isDown: true, time: 0).isEmpty, "press does not switch")
    check(m.modifier(keyCode: 56, isDown: false, time: 0.1).isEmpty, "release defers single")
    check(m.advance(time: 0.419).isEmpty, "single waits 320ms")
    check(m.advance(time: 0.421) == [.switchLayout], "single fires after window")
    check(m.advance(time: 0.8).isEmpty, "single fires once")
    m.reset()
    _ = m.modifier(keyCode: 56, isDown: true, time: 1)
    _ = m.modifier(keyCode: 56, isDown: false, time: 1.1)
    _ = m.modifier(keyCode: 56, isDown: true, time: 1.2)
    check(m.nextDeadline == nil, "defer timer while second press held")
    check(m.modifier(keyCode: 56, isDown: false, time: 1.3) == [.correctText], "same-side double corrects")
    check(m.advance(time: 2).isEmpty, "double does not leak single")
    m.reset()
    _ = m.modifier(keyCode: 56, isDown: true, time: 0)
    _ = m.modifier(keyCode: 56, isDown: false, time: 0.05)
    _ = m.modifier(keyCode: 60, isDown: true, time: 0.1)
    check(m.modifier(keyCode: 60, isDown: false, time: 0.15).isEmpty, "different-side releases are not double")
    check(m.advance(time: 0.5) == [.switchLayout, .switchLayout], "different-side taps remain two singles")
    m.reset()
    _ = m.modifier(keyCode: 56, isDown: true, time: 0)
    check(m.modifier(keyCode: 60, isDown: true, time: 0.05) == [.toggleAutomatic], "both shift chord")
    check(m.modifier(keyCode: 60, isDown: true, time: 0.06).isEmpty, "duplicate down does not toggle twice")
    check(m.modifier(keyCode: 56, isDown: false, time: 0.1).isEmpty, "chord release first")
    check(m.modifier(keyCode: 60, isDown: false, time: 0.15).isEmpty, "chord release second")
    check(m.advance(time: 1).isEmpty, "chord has no residual singles")
    m.reset()
    _ = m.modifier(keyCode: 58, isDown: true, time: 0)
    check(m.modifier(keyCode: 58, isDown: false, time: 0.1) == [.correctText], "option tap")
    m.reset()
    _ = m.modifier(keyCode: 56, isDown: true, time: 0)
    m.keyUsed()
    check(m.modifier(keyCode: 56, isDown: false, time: 0.1).isEmpty, "shift typing invalidates tap")
    check(m.advance(time: 1).isEmpty, "typing no late single")
    m.reset()
    _ = m.modifier(keyCode: 56, isDown: true, time: 0)
    check(m.modifier(keyCode: 56, isDown: false, time: 0.451).isEmpty, "long hold ignored")
    check(m.advance(time: 1).isEmpty, "long hold no late action")
    m.reset()
    _ = m.modifier(keyCode: 56, isDown: true, time: 0, hasOtherModifiers: true)
    check(m.modifier(keyCode: 56, isDown: false, time: 0.1).isEmpty, "command/control modified tap ignored")
    m.reset()
    _ = m.modifier(keyCode: 56, isDown: true, time: 0)
    _ = m.modifier(keyCode: 58, isDown: true, time: 0.05)
    _ = m.modifier(keyCode: 58, isDown: false, time: 0.1)
    check(m.modifier(keyCode: 56, isDown: false, time: 0.15).isEmpty, "shift plus option ignored")
    check(m.advance(time: 1).isEmpty, "mixed modifiers no late action")
    m.reset()
    _ = m.modifier(keyCode: 56, isDown: true, time: 0)
    _ = m.modifier(keyCode: 56, isDown: false, time: 0.1)
    m.reset()
    check(m.advance(time: 1).isEmpty, "focus reset cancels pending single")
    check(m.modifier(keyCode: 56, isDown: false, time: 1.1).isEmpty, "unpaired release ignored")
    m = ModifierGesture(singleShift: false, optionTap: false, bothShiftPause: false)
    _ = m.modifier(keyCode: 60, isDown: true, time: 0)
    _ = m.modifier(keyCode: 60, isDown: false, time: 0.1)
    check(m.advance(time: 1).isEmpty, "single disabled")
    _ = m.modifier(keyCode: 61, isDown: true, time: 2)
    check(m.modifier(keyCode: 61, isDown: false, time: 2.1).isEmpty, "option disabled")
    _ = m.modifier(keyCode: 56, isDown: true, time: 3)
    check(m.modifier(keyCode: 60, isDown: true, time: 3.1).isEmpty, "chord disabled")
    _ = m.modifier(keyCode: 56, isDown: false, time: 3.2)
    _ = m.modifier(keyCode: 60, isDown: false, time: 3.3)
    check(m.advance(time: 4).isEmpty, "disabled chord does not become singles")
    m.reset()
    _ = m.modifier(keyCode: 56, isDown: true, time: 10)
    check(m.modifier(keyCode: 56, isDown: false, time: 9).isEmpty, "nonmonotonic clock resets")
    check(m.advance(time: 11).isEmpty, "invalid time no later action")
    m = ModifierGesture(optionTap: true, bothShiftPause: true)
    _ = m.modifier(keyCode: 58, isDown: true, time: 0)
    m.keyUsed()
    check(m.modifier(keyCode: 58, isDown: false, time: 0.1).isEmpty, "option plus typing ignored")
    m.reset()
    _ = m.modifier(keyCode: 61, isDown: true, time: 0)
    check(m.modifier(keyCode: 61, isDown: false, time: 0.451).isEmpty, "long option ignored")
    m.reset()
    _ = m.modifier(keyCode: 60, isDown: true, time: 0)
    check(m.modifier(keyCode: 56, isDown: true, time: 0.1) == [.toggleAutomatic], "reverse-order shift chord")
    m.reset()
    _ = m.modifier(keyCode: 56, isDown: true, time: 0.9)
    _ = m.modifier(keyCode: 56, isDown: false, time: 1)
    _ = m.modifier(keyCode: 56, isDown: true, time: 1.1)
    check(m.modifier(keyCode: 56, isDown: false, time: 1.32) == [.correctText], "inclusive double boundary at 320ms")
    m.reset()
    _ = m.modifier(keyCode: 56, isDown: true, time: 0)
    _ = m.modifier(keyCode: 56, isDown: false, time: 0.1)
    m.keyUsed()
    check(m.advance(time: 1).isEmpty, "ordinary key cancels pending single after release")
    return results
}
